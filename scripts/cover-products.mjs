/**
 * Builds the cover wordings and listings page from the Nexus Mutual API.
 *
 * Shared by the generator (npm run docs:wordings) and by check 6 in
 * check-contract-docs.mjs, so the check compares the committed page with
 * exactly what the generator would write.
 *
 * Every product type with a current listing gets its wording, so a holder can
 * always find the terms they are covered under. Only public listings are
 * named. A private listing is a custom deal with named parties, so it stays
 * out of a public index, and a product type whose current listings are all
 * private shows its wording alone.
 */

import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const API = process.env.NEXUS_API_URL ?? 'https://api.nexusmutual.io/v2';
export const PAGE = path.join(ROOT, 'docs/overview/cover-products/cover-wordings.md');

const fetchJson = async url => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  return response.json();
};

/**
 * Product types with at least one current listing, sorted by name, each with
 * its public listings. `cid` is null when the product type records no
 * wording, which the check reports rather than hiding.
 */
export const loadCoverProducts = async () => {
  const [types, products] = await Promise.all([
    fetchJson(`${API}/product-types`),
    fetchJson(`${API}/products`),
  ]);

  const listingsByType = new Map();
  for (const p of products) {
    if (p.isDeprecated) continue;
    if (!listingsByType.has(p.productType)) listingsByType.set(p.productType, []);
    if (!p.isPrivate) listingsByType.get(p.productType).push({ id: p.id, name: p.name.trim() });
  }

  const byName = (a, b) => a.name.localeCompare(b.name) || a.id - b.id;

  return types
    .filter(t => listingsByType.has(t.id))
    .map(t => ({
      id: t.id,
      name: t.name,
      cid: t.metadata || null,
      listings: listingsByType.get(t.id).sort(byName),
    }))
    .sort(byName);
};

// Listing names come from the API, so escape what Markdown or MDX would read
// as syntax inside a table cell.
const cell = text => text.replace(/[\\|<>{}[\]*_`]/g, c => `\\${c}`);

export const renderPage = groups => {
  const sections = groups.map(g => {
    const wording = g.cid
      ? `[Cover wording](${API}/ipfs/${g.cid})`
      : 'No wording is recorded for this product.';
    if (!g.listings.length) return `## ${g.name}\n\n${wording}\n`;
    const rows = g.listings.map(l => `| ${l.id} | ${cell(l.name)} |`).join('\n');
    return `## ${g.name}\n\n${wording}\n\n| Product ID | Listing |\n| ---: | --- |\n${rows}\n`;
  });

  return `---
sidebar_position: 3
description: The cover wording for every Nexus Mutual product, and every public listing with its product ID.
---

# Cover wordings and listings

The cover wording is the document a claim is assessed against. It defines what is covered, what is excluded, what evidence is required, and how long after a loss a claim can be filed.

Each product below links the wording the protocol currently records for it. Where a product has public listings, they are listed with their product IDs. Read the wording for the product you hold before buying and before claiming.

<!-- Generated by npm run docs:wordings from the Nexus Mutual API. Do not edit by hand. -->

${sections.join('\n')}`;
};
